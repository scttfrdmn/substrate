package emulator

import (
	"bytes"
	"encoding/json"
	"fmt"
	"go/format"
	"strings"
	"text/template" // nosemgrep
)

// fixtureTemplate is the Go test file [GenerateTestFixture] writes.
//
// The fixture embeds the recorded events and replays them in process through
// [TestServer.ReplayEvents] rather than re-sending HTTP requests. That keeps everything
// an event records and a re-sent request would lose: the recorded request ID (and so
// every identifier minted from it), the recorded clock, the method, the query
// parameters, the X-Amz-Target and other headers, and the parsed form of a Query-protocol
// request, which is what the iam, sts, sqs and sns plugins read.
var fixtureTemplate = template.Must(template.New("fixture").Parse(`// Code generated by substrate's fixture export. DO NOT EDIT.
//
// The events replay into a test server started with the options below and no others:
// no fault rules armed, and no quota or consistency enforcement. A recorded refusal that
// only one of those produced replays as a difference.

package {{.Package}}

import (
{{- if .EventCount}}
	"encoding/json"
{{- end}}
	"testing"
{{- if .EventCount}}

	"github.com/scttfrdmn/substrate/emulator"
{{- end}}
)
{{if .EventCount}}
// {{.Prefix}}Events are the {{.EventCount}} recorded event(s) {{.TestName}} replays.
const {{.Prefix}}Events = {{.EventsLit}}

// {{.Prefix}}Allow lists the fields {{.TestName}} lets differ from the recording, as
// emulator.AssertReplayMatches patterns. It is empty because a replay reproduces the
// recorded request IDs, minted identifiers and clock.
var {{.Prefix}}Allow = []string{}
{{end}}
// {{.TestName}} replays a recorded substrate session into a fresh test server and fails
// on any difference from the recording.
func {{.TestName}}(t *testing.T) {
{{- if .EventCount}}
	var events []*emulator.Event
	if err := json.Unmarshal([]byte({{.Prefix}}Events), &events); err != nil {
		t.Fatalf("decode recorded events: %v", err)
	}
	ts := emulator.StartTestServer(t{{range .ServerOptions}}, {{.}}{{end}})
	results := ts.ReplayEvents(t, events)
	emulator.AssertReplayMatches(t, results, {{.Prefix}}Allow...)
{{- else}}
	t.Skip("the exported stream held no events")
{{- end}}
}
`))

// GenerateTestFixture returns the gofmt-formatted source of a Go test file that replays
// events, a recorded stream, and fails on any difference from the recording.
//
// The file embeds the events as JSON and replays them in process with
// [TestServer.ReplayEvents], asserting with [AssertReplayMatches]. It imports
// github.com/scttfrdmn/substrate/emulator, so packageName must not be emulator itself.
//
// An event that cannot be replayed is an error: one recorded without
// event_store.include_bodies, or whose request body was over event_store.max_body_bytes.
// A fixture built from it could only report the event as unverified.
func GenerateTestFixture(events []*Event, packageName, testName string) (string, error) {
	return generateTestFixture(events, packageName, testName, nil)
}

// generateTestFixture is [GenerateTestFixture] with the [TestServerOption] expressions
// the fixture's server is started with, which [Server.handleDebugExport] derives from
// the recording server's configuration.
func generateTestFixture(events []*Event, packageName, testName string, serverOptions []string) (string, error) {
	for _, ev := range events {
		switch {
		case ev.RequestBodyOmitted != nil:
			return "", fmt.Errorf("event seq %d (%s/%s): request body of %d bytes was over event_store.max_body_bytes and was not recorded",
				ev.Sequence, ev.Service, ev.Operation, ev.RequestBodyOmitted.Length)
		case ev.Request == nil:
			return "", fmt.Errorf("event seq %d (%s/%s) has no recorded request; record with event_store.include_bodies",
				ev.Sequence, ev.Service, ev.Operation)
		}
	}

	data := struct {
		Package       string
		TestName      string
		Prefix        string
		EventCount    int
		EventsLit     string
		ServerOptions []string
	}{
		Package:       packageName,
		TestName:      testName,
		Prefix:        lowerFirst(strings.ReplaceAll(testName, "_", "")),
		EventCount:    len(events),
		ServerOptions: serverOptions,
	}
	if len(events) > 0 {
		raw, err := json.MarshalIndent(events, "", "\t")
		if err != nil {
			return "", fmt.Errorf("encode fixture events: %w", err)
		}
		data.EventsLit = rawStringLiteral(string(raw))
	}

	var buf bytes.Buffer
	if err := fixtureTemplate.Execute(&buf, data); err != nil {
		return "", fmt.Errorf("execute fixture template: %w", err)
	}
	formatted, err := format.Source(buf.Bytes())
	if err != nil {
		return "", fmt.Errorf("format fixture (is %q a valid package name and %q a valid test name?): %w",
			packageName, testName, err)
	}
	return string(formatted), nil
}

// rawStringLiteral returns a Go constant expression for s: a raw string literal, with
// each backtick spliced in as an interpreted literal.
func rawStringLiteral(s string) string {
	return "`" + strings.ReplaceAll(s, "`", "` + \"`\" + `") + "`"
}
