package emulator

import "net/http"

// Athena pages two listings by an array offset, and a token it never issued is refused (#1086).
//
// ListQueryExecutions and ListWorkGroups both decoded their NextToken with the pre-#915 idiom —
// base64.StdEncoding.DecodeString then strconv.Atoi, both errors discarded — so a token substrate
// could not have issued left the offset at zero and the operation answered a well-formed **page
// one**. That is the one wrong answer a paginating caller cannot detect: a loop that runs until the
// token comes back empty is handed the first page again, so it either spins or processes the same
// records twice, and nothing in the response says so. Both now share [decodeOffsetPaginationToken],
// which defines issuability as a round trip through the encoder, and [pageByOffsetToken], which was
// already the cut both had written out by hand.
//
// # What the pages publish, and what is substrate's reading
//
// Athena is the best-documented of #1086's sites, because its NextToken description says where a
// token comes from: *"A token generated by the Athena service that specifies where to continue
// pagination if a previous request was truncated. To obtain the next set of pages, pass in the
// NextToken from the response object of the previous page call."* — published verbatim on both
// operations, for the request parameter and again for the response element. A token no previous
// response carried is therefore not the thing the parameter is documented to accept, which is a
// stronger footing than the other sites in this class have.
//
// The code is [athenaInvalidPaginationToken]'s InvalidRequestException/400, published in **both**
// operations' own Errors sections and glossed *"Indicates that something is wrong with the input to
// the request. For example, a required parameter may be missing or out of range."* — so it is this
// operation's own vocabulary and not one borrowed from a sibling, which is what [#671]'s scope
// decision requires. It is already this plugin's code for a malformed input at five other doors.
//
// What remains substrate's reading is only that this particular input problem is the one that gloss
// covers: neither page publishes a code AWS attributes to a pagination token, and Athena's
// common-errors page carries nothing about one either.
//
// The published Length constraint on NextToken — minimum 1, maximum 1024 on both the request and the
// response — is enforced at both ends (#1185). The maximum needs no check of its own: the encoder emits
// an offset in decimal base64, a handful of characters, so every token longer than 1024 already fails
// the round trip. The minimum does, because a round trip cannot see it — an empty string is what
// [decodeOffsetPaginationToken] reads as the start of the listing. So the member is decoded as a
// pointer, and an explicit `"NextToken": ""` is refused with the same code while an absent member is
// still the start of the listing.
//
// # Ordering
//
// The token is decoded before any state is read, which is #887's criterion: a refusal must not depend
// on how much state happens to exist, and a store failure must not be reported as a 500 for a request
// that was already refusable. Neither operation resolves a resource first, so neither has a NotFound
// whose precedence has to be preserved — ListQueryExecutions' WorkGroup is a filter, not a lookup, and
// an absent workgroup yields an empty list rather than a refusal.
//
// The test counts reads and requires the refused request to have performed none — see
// TestPaginationToken_AthenaListQueryExecutionsRefusesATokenItDidNotIssue. Until #1175,
// [athenaLoadStringIndex] reported a store failure as an empty index, which is why a sealed store
// could not assert the ordering; it now returns the failure, so a sealed read is an error.
//
// # MaxResults: two ranges, not one (#1185)
//
// This section was headed "Not fixed here" until #1185. The two handlers shared one preamble —
// `if maxResults <= 0 { maxResults = 50 }` — which encoded an assumption the pages contradict:
// API_ListQueryExecutions publishes "Valid Range: Minimum value of 0. Maximum value of 50." and
// API_ListWorkGroups "Valid Range: Minimum value of 1. Maximum value of 50." So one shared line could
// not be right for both. A 0 on ListQueryExecutions is a legal value that was rewritten to the widest
// page; a 0 on ListWorkGroups is out of range and was accepted; and above 50 nothing was enforced.
//
// Each operation now has its own [pageSizeRange], and a value outside it is refused with
// InvalidRequestException/400, the code both pages publish and gloss as "a required parameter may be
// missing or out of range" — this case named outright, so the refusal is the page's own vocabulary.
// An absent MaxResults keeps [athenaListDefaultPageSize], so every recorded request that omitted it
// replays byte-identically.
//
// **A MaxResults of 0 on ListQueryExecutions is honoured as written**: the page carries no query
// execution IDs, and carries a NextToken that resumes at the same position when records remain there
// (none when they do not). Neither page says what 0 means — unlike Step Functions', no sentence maps
// it to a default — so substrate answers what the caller asked for: at most zero items. The response
// element publishes `QueryExecutionIds` with "Array Members: Minimum number of 1 item", which a zero
// page cannot meet. Substrate reads that minimum as describing a page with something on it rather than
// as forbidding the empty list, because the same empty list is also the only honest answer for a
// workgroup with no queries, and substrate already gave it there; the alternative readings — refusing
// a value the request's own range permits, or emitting an item the caller did not ask for — each
// contradict a published constraint more directly than an empty list does.
//
// [#671]: https://github.com/scttfrdmn/substrate/issues/671

// athenaListDefaultPageSize is the page size both listings apply when MaxResults is absent.
//
// Neither page publishes a default, so this is substrate's choice and not a verified figure. It is the
// published *maximum* of both operations' Valid Range, which is the most a caller can ask for and so
// the largest page an unbounded request could legitimately receive. Named rather than repeated as a
// literal so that the unverified part of the page size is visible at both sites.
const athenaListDefaultPageSize = 50

// athenaListQueryExecutionsMaxResults and athenaListWorkGroupsMaxResults are the two operations'
// published MaxResults ranges, which differ at the low end; see this file's comment.
var (
	athenaListQueryExecutionsMaxResults = pageSizeRange{member: "MaxResults", min: 0, max: 50, def: athenaListDefaultPageSize}
	athenaListWorkGroupsMaxResults      = pageSizeRange{member: "MaxResults", min: 1, max: 50, def: athenaListDefaultPageSize}
)

// athenaListParams resolves a listing's MaxResults and NextToken, refusing either when it is not one
// the operation accepts.
//
// MaxResults is judged first, then the token; both before any state is read, for the ordering this
// file records. An explicit empty NextToken is refused for the published minimum length of 1, while an
// absent one is the start of the listing.
func athenaListParams(operation string, r pageSizeRange, maxResults *int, nextToken *string) (int, int, *AWSError) {
	size, ok := r.resolve(maxResults)
	if !ok {
		return 0, 0, &AWSError{
			Code:       "InvalidRequestException",
			Message:    r.outOfRange(*maxResults),
			HTTPStatus: http.StatusBadRequest,
		}
	}
	if nextToken == nil {
		return size, 0, nil
	}
	if *nextToken == "" {
		return 0, 0, athenaInvalidPaginationToken(operation)
	}
	offset, ok := decodeOffsetPaginationToken(*nextToken)
	if !ok {
		return 0, 0, athenaInvalidPaginationToken(operation)
	}
	return size, offset, nil
}

// athenaPageIDs cuts one ListQueryExecutions page, honouring a MaxResults of 0 as a page with no items.
//
// [pageByOffsetToken] reads a page size of 0 as "no limit", which is the opposite of what a caller who
// sent 0 asked for, so that case is answered here: an empty page, and a token that resumes at the same
// offset when records remain from it. A past-the-end offset still clamps to an empty final page with no
// token, as it does for every other size.
func athenaPageIDs(ids []string, offset, maxResults int) ([]string, string) {
	if maxResults > 0 {
		return pageByOffsetToken(ids, offset, maxResults)
	}
	if offset >= len(ids) {
		return []string{}, ""
	}
	return []string{}, encodeOffsetPaginationToken(offset)
}

// athenaInvalidPaginationToken refuses a NextToken that no previous call to operation returned.
//
// The operation name is in the message because a token from the *other* Athena listing is one of the
// ways a caller arrives here: both encode an offset the same way, so ListWorkGroups' token decodes
// cleanly under ListQueryExecutions and would otherwise index into the wrong listing. The published
// gloss is not restated, because a caller told that something is wrong with its input cannot tell
// which parameter AWS means, and NextToken is the only one this refusal can be about.
func athenaInvalidPaginationToken(operation string) *AWSError {
	return &AWSError{
		Code:       "InvalidRequestException",
		Message:    "NextToken is not a token returned by a previous " + operation + " request",
		HTTPStatus: http.StatusBadRequest,
	}
}
