// Command gen-service-reference keeps the service reference's index in sync with the live
// plugin registry, so the documented plugin list and counts cannot drift from the
// implementation (#364).
//
// It boots the default plugin registry and renders two things from it:
//
//   - the coverage matrix in docs/services.md, between the marker comments
//     <!-- BEGIN GENERATED COVERAGE MATRIX --> and <!-- END GENERATED COVERAGE MATRIX -->,
//     one row per plugin linking to its page, docs/reference/<plugin>.md. Everything
//     outside the markers is hand-written and left untouched;
//   - docs/.vitepress/services-sidebar.json, the sidebar's Services group.
//
// It then checks what the index promises but does not generate: that every entry of the
// frozen docs/.vitepress/legacy-anchors.json still lands on a heading (see
// [checkLegacyAnchors]), and that every link between docs pages names an anchor its target
// page has (see [checkLinks]).
//
// Per-plugin display names and protocols come from the emulator's own
// routing table ([emu.PluginRoutingCatalog], emulator/routing.go); the tool fails
// if a registered plugin has no entry there (or an entry names a plugin that is
// not registered), which is what a CI drift check enforces.
//
// The per-plugin routed-operation count in the matrix comes from the operation
// catalog ([emu.RoutedOperations], generated by cmd/gen-operation-catalog from each
// plugin's dispatch switch), so the documented count is a projection of the router
// and not a figure anyone maintains by hand — two careful hand counts of the same
// tree disagreed by five, which is what #1095 exists to end. The catalog is checked
// against the registry in both directions here too, so a plugin the catalog does not
// cover fails this tool rather than rendering a silent zero.
//
// Usage:
//
//	go run ./cmd/gen-service-reference                # rewrite the matrix and the sidebar
//	go run ./cmd/gen-service-reference -check         # exit non-zero if either is out of date
//
// The sidebar is written beside the index, under its directory's .vitepress, so -out
// alone places both.
package main

import (
	"bytes"
	"context"
	"encoding/json"
	"errors"
	"flag"
	"fmt"
	"io"
	"io/fs"
	"log/slog"
	"os"
	"path/filepath"
	"sort"
	"strings"
	"time"

	emu "github.com/scttfrdmn/substrate/emulator"
)

const (
	beginMarker = "<!-- BEGIN GENERATED COVERAGE MATRIX -->"
	endMarker   = "<!-- END GENERATED COVERAGE MATRIX -->"
)

// routing is the per-plugin routing and documentation metadata, read from the
// emulator's own table (emulator/routing.go) rather than kept in a second copy
// here. One table then serves three consumers: this matrix, the drift check
// below, and the reachability sweep test that asserts every identifier in it
// resolves to a registered plugin (#739). A duplicate map in cmd/ could agree
// with the docs while disagreeing with what an SDK actually sends, which is the
// class of failure #739 exists to close.
var routing = emu.PluginRoutingCatalog()

func main() {
	if err := run(os.Args[1:], os.Stdout); err != nil {
		fmt.Fprintln(os.Stderr, "gen-service-reference:", err)
		os.Exit(1)
	}
}

// output is one file this tool renders: its path, and how to render it from what the
// file holds now (the matrix is spliced into hand-written prose; the sidebar is whole).
type output struct {
	path   string
	render func(existing []byte) ([]byte, error)
}

func run(args []string, stdout io.Writer) error {
	flags := flag.NewFlagSet("gen-service-reference", flag.ContinueOnError)
	flags.SetOutput(stdout)
	check := flags.Bool("check", false, "exit non-zero if a file is out of date instead of writing it")
	out := flags.String("out", filepath.Join("docs", "services.md"), "path to the service reference index")
	if err := flags.Parse(args); err != nil {
		return fmt.Errorf("parse flags: %w", err)
	}
	docsDir := filepath.Dir(*out)

	names, err := registeredPlugins()
	if err != nil {
		return err
	}
	outputs := []output{
		{path: *out, render: func(existing []byte) ([]byte, error) { return replaceMatrix(existing, names) }},
		{path: filepath.Join(docsDir, ".vitepress", "services-sidebar.json"),
			render: func([]byte) ([]byte, error) { return renderSidebar(names) }},
	}
	for _, o := range outputs {
		if err := generate(o, *check, stdout); err != nil {
			return err
		}
	}

	if err := checkLegacyAnchors(docsDir); err != nil {
		return err
	}
	return checkLinks(docsDir)
}

// generate renders one output and either writes it or, with check, refuses a file that
// differs from its rendering. A missing file renders from nothing: the sidebar is whole,
// and the index refuses for want of its markers.
func generate(o output, check bool, stdout io.Writer) error {
	existing, err := os.ReadFile(o.path)
	if err != nil && !errors.Is(err, fs.ErrNotExist) {
		return fmt.Errorf("read %s: %w", o.path, err)
	}
	updated, err := o.render(existing)
	if err != nil {
		return fmt.Errorf("%s: %w", o.path, err)
	}
	switch {
	case bytes.Equal(existing, updated):
		if !check {
			_, _ = fmt.Fprintf(stdout, "%s already up to date\n", o.path)
		}
		return nil
	case check:
		return fmt.Errorf("%s is out of date; run `make docs-reference` and commit the result", o.path)
	}
	if err := os.WriteFile(o.path, updated, 0o644); err != nil { //nolint:gosec // docs file, world-readable is fine.
		return fmt.Errorf("write %s: %w", o.path, err)
	}
	_, _ = fmt.Fprintf(stdout, "updated %s\n", o.path)
	return nil
}

// registeredPlugins boots the default registry and returns the sorted plugin
// names, verifying that metadata is complete in both directions.
func registeredPlugins() ([]string, error) {
	reg := emu.NewPluginRegistry()
	state := emu.NewMemoryStateManager()
	tc := emu.NewTimeController(time.Unix(0, 0).UTC())
	logger := emu.NewDefaultLogger(slog.LevelError, false)
	store := emu.NewEventStore(emu.EventStoreConfig{Enabled: false})

	if err := emu.RegisterDefaultPlugins(context.Background(), reg, state, tc, logger, store, nil); err != nil {
		return nil, fmt.Errorf("register default plugins: %w", err)
	}
	names, err := checkRouting(reg.Names(), routing)
	if err != nil {
		return nil, err
	}
	return names, checkCatalog(names, emu.RoutedServices())
}

// checkCatalog verifies that the operation catalog covers exactly the registered
// plugins. It takes both lists as parameters for the same reason checkRouting does:
// an untested drift check is one nobody knows still fires (#739).
//
// The catalog is generated from each plugin's dispatch switch, so this refusal only
// fires when the generated file is stale — and `make operation-catalog-check` runs
// before this tool in CI so that the failure names the right file. The refusal is
// still worth having: without it, a plugin the catalog does not cover would render a
// zero in the matrix, which reads as "routes no operations" rather than as an error.
func checkCatalog(registered, cataloged []string) error {
	inCatalog := make(map[string]bool, len(cataloged))
	for _, n := range cataloged {
		inCatalog[n] = true
	}
	for _, n := range registered {
		if !inCatalog[n] {
			return fmt.Errorf("plugin %q is registered but absent from the operation catalog; run `make operation-catalog` and commit the result", n)
		}
	}
	isRegistered := make(map[string]bool, len(registered))
	for _, n := range registered {
		isRegistered[n] = true
	}
	for _, n := range cataloged {
		if !isRegistered[n] {
			return fmt.Errorf("operation catalog covers %q, which is not a registered plugin; run `make operation-catalog` and commit the result", n)
		}
	}
	return nil
}

// checkRouting verifies that the routing table and the registered plugin names
// agree in both directions and returns the names sorted. It takes the table as a
// parameter rather than reading the package-level [routing] so that both refusals
// are reachable from a test — the drift check is the whole point of the -check
// flag, and an untested drift check is one nobody knows still fires (#739).
func checkRouting(names []string, table map[string]emu.PluginRouting) ([]string, error) {
	registered := make(map[string]bool, len(names))
	for _, n := range names {
		registered[n] = true
		if _, ok := table[n]; !ok {
			return nil, fmt.Errorf("plugin %q is registered but has no entry in emulator/routing.go; add one, citing the source of its target prefix, hosts and signing names", n)
		}
	}
	for n := range table {
		if !registered[n] {
			return nil, fmt.Errorf("routing entry %q does not correspond to a registered plugin; remove it from emulator/routing.go", n)
		}
	}
	sorted := make([]string, len(names))
	copy(sorted, names)
	sort.Strings(sorted)
	return sorted, nil
}

// replaceMatrix swaps the content between the begin/end markers in doc for a
// freshly rendered coverage matrix, leaving everything else untouched.
func replaceMatrix(doc []byte, names []string) ([]byte, error) {
	begin := bytes.Index(doc, []byte(beginMarker))
	end := bytes.Index(doc, []byte(endMarker))
	if begin < 0 || end < 0 || end < begin {
		return nil, fmt.Errorf("could not find %q ... %q markers in the document", beginMarker, endMarker)
	}

	total := 0
	for _, n := range names {
		total += len(emu.RoutedOperations(n))
	}

	var matrix bytes.Buffer
	fmt.Fprintln(&matrix, beginMarker)
	fmt.Fprintf(&matrix, "Substrate ships **%d built-in service plugins** routing **%d operations**. This\n", len(names), total)
	fmt.Fprintln(&matrix, "section is generated from the plugin registry and the operation catalog")
	fmt.Fprintln(&matrix, "(`make docs-reference`), so the counts and the plugin list cannot drift from the")
	fmt.Fprintln(&matrix, "implementation: the catalog is itself generated from each plugin's dispatch switch")
	fmt.Fprintln(&matrix, "(`make operation-catalog`) and is readable at run time through")
	fmt.Fprintln(&matrix, "`emulator.RoutedServices` and `emulator.RoutedOperations`. The live plugin count is")
	fmt.Fprintln(&matrix, "also available from the `/ready` endpoint (`curl http://localhost:4566/ready`).")
	fmt.Fprintln(&matrix, "Each row links to the plugin's page, which carries its operation, CloudFormation and")
	fmt.Fprintln(&matrix, "cost detail.")
	fmt.Fprintln(&matrix)
	fmt.Fprintln(&matrix, "Two plugins route **0** operations, and that is their protocol rather than a gap:")
	fmt.Fprintln(&matrix, "`execute-api` serves a deployed API's own routes (AWS's action for it is the single")
	fmt.Fprintln(&matrix, "`execute-api:Invoke`), and `opensearch` dispatches on the HTTP method plus path")
	fmt.Fprintln(&matrix, "shape, as AWS's own per-verb `es:ESHttp*` actions reflect.")
	fmt.Fprintln(&matrix)
	fmt.Fprintln(&matrix, "| # | Service | Plugin name | Protocol | Operations |")
	fmt.Fprintln(&matrix, "|---|---------|-------------|----------|-----------:|")
	for i, n := range names {
		m := routing[n]
		fmt.Fprintf(&matrix, "| %d | [%s](%s) | `%s` | %s | %d |\n",
			i+1, m.Display, pageLink(n), n, m.Protocol, len(emu.RoutedOperations(n)))
	}
	fmt.Fprint(&matrix, endMarker)

	var result bytes.Buffer
	result.Write(doc[:begin])
	result.Write(matrix.Bytes())
	result.Write(doc[end+len(endMarker):])
	return result.Bytes(), nil
}

// pageLink is the site route of a plugin's reference page, docs/reference/<plugin>.md. The
// page is named by the registry name so that cmd/check-operation-docs can pair the two
// without a hand-kept map.
func pageLink(plugin string) string { return "/reference/" + plugin }

// sidebarItem is one entry of a VitePress sidebar group.
type sidebarItem struct {
	Text string `json:"text"`
	Link string `json:"link"`
}

// renderSidebar renders docs/.vitepress/services-sidebar.json, which config.mts imports as
// the Services group: one entry per registered plugin, labeled as the matrix labels it and
// ordered by that label, so a reader scanning for "Lambda" finds it under L rather than
// under the registry name.
func renderSidebar(names []string) ([]byte, error) {
	items := make([]sidebarItem, 0, len(names))
	for _, n := range names {
		items = append(items, sidebarItem{Text: routing[n].Display, Link: pageLink(n)})
	}
	sort.SliceStable(items, func(i, j int) bool {
		a, b := strings.ToLower(items[i].Text), strings.ToLower(items[j].Text)
		if a != b {
			return a < b
		}
		return items[i].Link < items[j].Link
	})
	var buf bytes.Buffer
	enc := json.NewEncoder(&buf)
	enc.SetEscapeHTML(false)
	enc.SetIndent("", "  ")
	if err := enc.Encode(items); err != nil {
		return nil, fmt.Errorf("encode sidebar: %w", err)
	}
	return buf.Bytes(), nil
}
