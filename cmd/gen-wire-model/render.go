// kindConst maps a botocore shape type to the generated constant.
var kindConst = map[string]string{
	"structure": "wireStructure",
	"list":      "wireList",
	"map":       "wireMap",
	"string":    "wireString",
	"blob":      "wireBlob",
	"integer":   "wireInteger",
	"long":      "wireInteger",
	"short":     "wireInteger",
	"byte":      "wireInteger",
	"float":     "wireFloat",
	"double":    "wireFloat",
	"boolean":   "wireBoolean",
	"timestamp": "wireTimestamp",
}

// locationConst maps a member's botocore location to the generated constant. A member with no
// location is in the body.
var locationConst = map[string]string{
	"":            "",
	"uri":         "wireInURI",
	"querystring": "wireInQuery",
	"header":      "wireInHeader",
	"headers":     "wireInHeaders",
	"statusCode":  "",
}

// stats summarizes what render produced, for the command's one-line report.
type stats struct {
	models, operations, shapes, ambiguous int
}

func (s stats) String() string {
	return fmt.Sprintf("%d models, %d operations, %d shapes, %d operations left out as ambiguous",
		s.models, s.operations, s.shapes, s.ambiguous)
}

// renderer assigns table indexes while walking the models.
type renderer struct {
	shapes    []string // rendered shape literals; index 0 is the unconstrained shape
	index     map[string]int
	enums     []string
	enumIdx   map[string]int
	patterns  []string
	patIdx    map[string]int
	constrain map[string]bool
}

// render produces the generated Go source for the snapshot.
func render(snap *snapshot) ([]byte, stats, error) {
	r := &renderer{
		shapes:    []string{"{}"},
		index:     map[string]int{},
		enums:     []string{""},
		enumIdx:   map[string]int{},
		patterns:  []string{""},
		patIdx:    map[string]int{},
		constrain: map[string]bool{},
	}
	modelNamesSorted := sortedKeys(snap.models)
	modelIdx := map[string]int{}
	for i, n := range modelNamesSorted {
		modelIdx[n] = i
	}

	type opEntry struct {
		model     string
		input     int
		method    string
		uri       string
		hasInput  bool
		operation string
	}
	ops := map[string][]opEntry{}
	var st stats
	st.models = len(snap.models)
	unmodelled := map[string]map[string]bool{}
	for p, list := range snap.manifest.Unmodelled {
		unmodelled[p] = map[string]bool{}
		for _, op := range list {
			unmodelled[p][op] = true
		}
	}
	for _, pm := range pluginModels {
		for _, op := range emulator.RoutedOperations(pm.plugin) {
			var in []string
			for _, mn := range pm.models {
				m := snap.models[mn]
				if m != nil && m.service.get("operations").get(op) != nil {
					in = append(in, mn)
				}
			}
			switch {
			case len(in) == 0:
				if !unmodelled[pm.plugin][op] && pm.unmodelled == "" {
					return nil, st, fmt.Errorf("%s routes %s, which the vendored snapshot neither holds nor lists as unmodelled; "+
						"run `make wire-model-fetch` to re-prune the snapshot to the routed operations", pm.plugin, op)
				}
				continue
			case len(in) > 1:
				st.ambiguous++
				continue
			}
			m := snap.models[in[0]]
			def := m.service.get("operations").get(op)
			e := opEntry{model: in[0], operation: op}
			if http := def.get("http"); http != nil && isREST(m) {
				e.method, e.uri = http.get("method").str(), http.get("requestUri").str()
			}
			if inShape := def.get("input").get("shape").str(); inShape != "" {
				idx, err := r.shape(m, inShape)
				if err != nil {
					return nil, st, err
				}
				e.input, e.hasInput = idx, true
			}
			ops[pm.plugin] = append(ops[pm.plugin], e)
			st.operations++
		}
	}
	st.shapes = len(r.shapes) - 1

	var b bytes.Buffer
	b.WriteString("// Code generated by cmd/gen-wire-model; DO NOT EDIT.\n//\n")
	fmt.Fprintf(&b, "// Source: botocore %s (https://github.com/boto/botocore, Apache-2.0), pruned to the\n", snap.manifest.Botocore)
	b.WriteString("// operations substrate routes and vendored under emulator/wiremodel.\n//\n")
	b.WriteString("// Regenerate with `make wire-model`; refresh the snapshot with `make wire-model-fetch`\n")
	b.WriteString("// (network).\n\npackage emulator\n\n")
	fmt.Fprintf(&b, "// wireModelVersion names the vendored snapshot. A recorded event carries it when the\n"+
		"// validation gate ran on the request; see [Event.ValidationModel].\nconst wireModelVersion = %q\n\n",
		"botocore/"+snap.manifest.Botocore)

	b.WriteString("// wireModels lists the vendored models, indexed by [wireOperation.Model].\n")
	b.WriteString("var wireModels = []wireModelInfo{ //nolint:gochecknoglobals // generated immutable table\n")
	for _, n := range modelNamesSorted {
		m := snap.models[n]
		fmt.Fprintf(&b, "\t{Name: %q, APIVersion: %q, Protocol: %q},\n", n, m.apiVersion,
			m.service.get("metadata").get("protocol").str())
	}
	b.WriteString("}\n\n")

	b.WriteString("// wireOperations maps a plugin and a routed operation to its input shape. An operation\n" +
		"// two of a plugin's models define is absent, as is one no model defines.\n")
	b.WriteString("var wireOperations = map[string]map[string]wireOperation{ //nolint:gochecknoglobals // generated immutable table\n")
	for _, plugin := range sortedKeys(ops) {
		fmt.Fprintf(&b, "\t%q: {\n", plugin)
		entries := ops[plugin]
		sort.Slice(entries, func(i, j int) bool { return entries[i].operation < entries[j].operation })
		for _, e := range entries {
			parts := []string{fmt.Sprintf("Model: %d", modelIdx[e.model])}
			if e.hasInput && e.input != 0 {
				parts = append(parts, fmt.Sprintf("Input: %d", e.input))
			}
			if e.method != "" {
				parts = append(parts, fmt.Sprintf("Method: %q", e.method), fmt.Sprintf("URI: %q", e.uri))
			}
			fmt.Fprintf(&b, "\t\t%q: {%s},\n", e.operation, strings.Join(parts, ", "))
		}
		b.WriteString("\t},\n")
	}
	b.WriteString("}\n\n")

	b.WriteString("// wireShapes holds every constrained input shape, indexed by [wireMember.Shape]. Index 0\n" +
		"// is the shape with no constraint.\n")
	b.WriteString("var wireShapes = []wireShape{ //nolint:gochecknoglobals // generated immutable table\n")
	for i, s := range r.shapes {
		fmt.Fprintf(&b, "\t/* %d */ %s,\n", i, s)
	}
	b.WriteString("}\n\n")

	b.WriteString("// wireEnums holds each enum's values, indexed by [wireShape.Enum]. Index 0 is no enum.\n")
	b.WriteString("var wireEnums = [][]string{ //nolint:gochecknoglobals // generated immutable table\n\tnil,\n")
	for _, e := range r.enums[1:] {
		fmt.Fprintf(&b, "\t{%s},\n", e)
	}
	b.WriteString("}\n\n")

	b.WriteString("// wirePatterns holds each pattern as the model writes it, indexed by [wireShape.Pattern].\n" +
		"// Index 0 is no pattern.\n")
	b.WriteString("var wirePatterns = []string{ //nolint:gochecknoglobals // generated immutable table\n\t\"\",\n")
	for _, p := range r.patterns[1:] {
		fmt.Fprintf(&b, "\t%s,\n", strconv.Quote(p))
	}
	b.WriteString("}\n")

	formatted, err := format.Source(b.Bytes())
	if err != nil {
		return nil, st, fmt.Errorf("format generated source: %w", err)
	}
	return formatted, st, nil
}

// isREST reports whether a model's protocol binds members to the URI, query string and headers.
func isREST(m *model) bool {
	switch m.service.get("metadata").get("protocol").str() {
	case "rest-json", "rest-xml":
		return true
	}
	return false
}

// constrained reports whether a shape carries a constraint or leads to one.
func (r *renderer) constrained(m *model, name string, seen map[string]bool) bool {
	out, _ := r.constrainedCut(m, name, seen)
	return out
}

// constrainedCut is [renderer.constrained], also reporting whether the walk cut a cycle. A
// false answer reached across a cut cycle is not memoized, because it was decided without the
// shape the cycle returns to; a true answer always is.
func (r *renderer) constrainedCut(m *model, name string, seen map[string]bool) (bool, bool) {
	key := m.name + "#" + name
	if v, ok := r.constrain[key]; ok {
		return v, false
	}
	if seen[key] {
		return false, true
	}
	seen[key] = true
	defer delete(seen, key)
	sh := m.service.get("shapes").get(name)
	if minBound(sh) != "" || sh.get("max") != nil || sh.get("enum") != nil || sh.get("pattern") != nil ||
		len(sh.get("required").elems()) > 0 {
		r.constrain[key] = true
		return true, false
	}
	cut := false
	var refs []string
	for _, mem := range sh.get("members").members() {
		refs = append(refs, mem.val.get("shape").str())
	}
	for _, k := range []string{"member", "key", "value"} {
		if ref := sh.get(k); ref != nil {
			refs = append(refs, ref.get("shape").str())
		}
	}
	for _, ref := range refs {
		v, c := r.constrainedCut(m, ref, seen)
		if v {
			r.constrain[key] = true
			return true, false
		}
		cut = cut || c
	}
	if !cut {
		r.constrain[key] = false
	}
	return false, cut
}

// minBound returns a shape's minimum as the model writes it, or "" when it bounds nothing: a
// length minimum of zero is no bound, while a range minimum of zero is one.
func minBound(sh *value) string {
	min := sh.get("min").number()
	if min == "" {
		return ""
	}
	switch sh.get("type").str() {
	case "string", "blob", "list", "map":
		if min == "0" {
			return ""
		}
	}
	return min
}

// shape returns the table index of a model's shape, rendering it on first use.
func (r *renderer) shape(m *model, name string) (int, error) {
	key := m.name + "#" + name
	if idx, ok := r.index[key]; ok {
		return idx, nil
	}
	sh := m.service.get("shapes").get(name)
	if sh == nil {
		return 0, fmt.Errorf("%s: shape %s is not in the snapshot", m.name, name)
	}
	kind, ok := kindConst[sh.get("type").str()]
	if !ok {
		return 0, fmt.Errorf("%s: shape %s has type %q; add it to kindConst and to emulator/wire_model.go",
			m.name, name, sh.get("type").str())
	}
	idx := len(r.shapes)
	r.index[key] = idx
	r.shapes = append(r.shapes, "") // reserved, so a recursive reference finds the index
	parts := []string{"Kind: " + kind}
	if min := minBound(sh); min != "" {
		parts = append(parts, fmt.Sprintf("Min: %q", min))
	}
	if max := sh.get("max").number(); max != "" {
		parts = append(parts, fmt.Sprintf("Max: %q", max))
	}
	if enum := sh.get("enum"); enum != nil {
		parts = append(parts, fmt.Sprintf("Enum: %d", r.enum(enum.strings())))
	}
	if pattern := sh.get("pattern").str(); pattern != "" {
		parts = append(parts, fmt.Sprintf("Pattern: %d", r.pattern(pattern)))
	}
	if sh.get("flattened").boolean() {
		parts = append(parts, "Flat: true")
	}
	if payload := sh.get("payload").str(); payload != "" {
		parts = append(parts, fmt.Sprintf("Payload: %q", payload))
	}
	for _, k := range []string{"member", "key", "value"} {
		ref := sh.get(k)
		if ref == nil {
			continue
		}
		field := map[string]string{"member": "Member", "key": "Key", "value": "Member"}[k]
		target := 0
		if r.constrained(m, ref.get("shape").str(), map[string]bool{}) {
			t, err := r.shape(m, ref.get("shape").str())
			if err != nil {
				return 0, err
			}
			target = t
		}
		var refParts []string
		if target != 0 {
			refParts = append(refParts, fmt.Sprintf("Shape: %d", target))
		}
		if ln := ref.get("locationName").str(); ln != "" {
			refParts = append(refParts, fmt.Sprintf("LocationName: %q", ln))
		}
		if len(refParts) > 0 {
			parts = append(parts, fmt.Sprintf("%s: wireRef{%s}", field, strings.Join(refParts, ", ")))
		}
	}
	required := map[string]bool{}
	for _, req := range sh.get("required").strings() {
		required[req] = true
	}
	var members []string
	for _, mem := range sh.get("members").members() {
		ref := mem.val
		target := ref.get("shape").str()
		isConstrained := r.constrained(m, target, map[string]bool{})
		if !required[mem.key] && !isConstrained {
			continue
		}
		t, err := r.shape(m, target)
		if err != nil {
			return 0, err
		}
		mp := []string{fmt.Sprintf("Name: %q", mem.key), fmt.Sprintf("Shape: %d", t)}
		if required[mem.key] {
			mp = append(mp, "Required: true")
		}
		loc, ok := locationConst[ref.get("location").str()]
		if !ok {
			return 0, fmt.Errorf("%s: %s.%s has location %q; add it to locationConst", m.name, name, mem.key, ref.get("location").str())
		}
		if loc != "" {
			mp = append(mp, "Location: "+loc)
		}
		if ln := ref.get("locationName").str(); ln != "" {
			mp = append(mp, fmt.Sprintf("LocationName: %q", ln))
		}
		if qn := ref.get("queryName").str(); qn != "" {
			mp = append(mp, fmt.Sprintf("QueryName: %q", qn))
		}
		if ref.get("flattened").boolean() {
			mp = append(mp, "Flat: true")
		}
		members = append(members, "{"+strings.Join(mp, ", ")+"}")
	}
	if len(members) > 0 {
		parts = append(parts, "Members: []wireMember{"+strings.Join(members, ", ")+"}")
	}
	r.shapes[idx] = "{" + strings.Join(parts, ", ") + "}"
	return idx, nil
}

func (r *renderer) enum(values []string) int {
	quoted := make([]string, len(values))
	for i, v := range values {
		quoted[i] = strconv.Quote(v)
	}
	lit := strings.Join(quoted, ", ")
	if idx, ok := r.enumIdx[lit]; ok {
		return idx
	}
	r.enums = append(r.enums, lit)
	r.enumIdx[lit] = len(r.enums) - 1
	return len(r.enums) - 1
}

func (r *renderer) pattern(p string) int {
	if idx, ok := r.patIdx[p]; ok {
		return idx
	}
	r.patterns = append(r.patterns, p)
	r.patIdx[p] = len(r.patterns) - 1
	return len(r.patterns) - 1
}
