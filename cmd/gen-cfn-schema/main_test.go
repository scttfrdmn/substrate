// rawFixture is a two-type specification in the shape AWS serves it, with the documentation
// members the tool drops.
const rawFixture = `{
  "ResourceSpecificationVersion": "9.9.9",
  "PropertyTypes": {"AWS::X::Y.Inner": {"Properties": {}}},
  "ResourceTypes": {
    "AWS::Z::Last": {"Documentation": "d", "Properties": {}},
    "AWS::A::First": {
      "Documentation": "d",
      "Attributes": {"Arn": {"PrimitiveType": "String"}, "Ids": {"Type": "List", "PrimitiveItemType": "String"},
                     "Obj": {"Type": "Inner"}},
      "Properties": {
        "Name": {"Required": true, "PrimitiveType": "String", "UpdateType": "Immutable"},
        "Tags": {"Type": "List", "ItemType": "Tag"},
        "Labels": {"Type": "Map", "PrimitiveItemType": "String"},
        "Config": {"Type": "Config"},
        "Doc": {"PrimitiveType": "Json"}
      }
    }
  }
}`

func gz(t *testing.T, b []byte) []byte {
	t.Helper()
	var buf bytes.Buffer
	zw := gzip.NewWriter(&buf)
	if _, err := zw.Write(b); err != nil {
		t.Fatal(err)
	}
	if err := zw.Close(); err != nil {
		t.Fatal(err)
	}
	return buf.Bytes()
}

// TestRefreshLoadRender walks the whole pipeline offline: a served specification, gzipped as the
// endpoint serves it or plain, is stripped into a snapshot that loads, and renders a table with
// every type, property and attribute, sorted, in the generated file's shape.
func TestRefreshLoadRender(t *testing.T) {
	for _, encoded := range []bool{true, false} {
		body := []byte(rawFixture)
		if encoded {
			body = gz(t, body)
		}
		srv := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, _ *http.Request) {
			_, _ = w.Write(body)
		}))
		dir := t.TempDir()
		if err := refresh(dir, srv.URL); err != nil {
			t.Fatalf("refresh (gzipped %v): %v", encoded, err)
		}
		first, err := os.ReadFile(filepath.Join(dir, snapshotName))
		if err != nil {
			t.Fatal(err)
		}
		if err := refresh(dir, srv.URL); err != nil {
			t.Fatal(err)
		}
		second, _ := os.ReadFile(filepath.Join(dir, snapshotName))
		if !bytes.Equal(first, second) {
			t.Error("a refresh that changes nothing must produce a byte-identical snapshot")
		}
		srv.Close()

		snap, err := load(filepath.Join(dir, snapshotName))
		if err != nil {
			t.Fatal(err)
		}
		if snap.Version != "9.9.9" || len(snap.ResourceTypes) != 2 {
			t.Fatalf("snapshot = %+v", snap)
		}
		src, err := render(snap)
		if err != nil {
			t.Fatal(err)
		}
		out := string(src)
		for _, want := range []string{
			"// Code generated by cmd/gen-cfn-schema; DO NOT EDIT.",
			`const cfnSchemaVersion = "9.9.9"`,
			`{"Name", true, cfnKindString}`,
			`{"Tags", false, cfnKindList}`,
			`{"Labels", false, cfnKindMap}`,
			`{"Config", false, cfnKindObject}`,
			`{"Doc", false, cfnKindJSON}`,
			`{"Ids", cfnKindList}`,
			`{"Obj", cfnKindObject}`,
		} {
			if !strings.Contains(out, want) {
				t.Errorf("generated source lacks %q", want)
			}
		}
		if strings.Index(out, "AWS::A::First") > strings.Index(out, "AWS::Z::Last") {
			t.Error("types are not sorted")
		}
		if strings.Index(out, `"Config"`) > strings.Index(out, `"Tags"`) {
			t.Error("properties are not sorted")
		}
	}
}

// TestRefreshFailures pins that a failed fetch writes nothing and says why.
func TestRefreshFailures(t *testing.T) {
	cases := map[string]http.HandlerFunc{
		"an HTTP error": func(w http.ResponseWriter, _ *http.Request) { w.WriteHeader(http.StatusNotFound) },
		"not JSON":      func(w http.ResponseWriter, _ *http.Request) { _, _ = w.Write([]byte("nope")) },
		"broken gzip":   func(w http.ResponseWriter, _ *http.Request) { _, _ = w.Write([]byte{0x1f, 0x8b, 0x00}) },
	}
	for name, h := range cases {
		t.Run(name, func(t *testing.T) {
			srv := httptest.NewServer(h)
			defer srv.Close()
			dir := t.TempDir()
			if err := refresh(dir, srv.URL); err == nil {
				t.Fatal("refresh succeeded")
			}
			if _, err := os.Stat(filepath.Join(dir, snapshotName)); !os.IsNotExist(err) {
				t.Error("a failed refresh wrote a snapshot")
			}
		})
	}
}

// TestLoadRefusesABadSnapshot pins the checks load makes before anything is generated.
func TestLoadRefusesABadSnapshot(t *testing.T) {
	dir := t.TempDir()
	write := func(name string, b []byte) string {
		p := filepath.Join(dir, name)
		if err := os.WriteFile(p, b, 0o600); err != nil {
			t.Fatal(err)
		}
		return p
	}
	for name, path := range map[string]string{
		"missing":     filepath.Join(dir, "absent.json.gz"),
		"not gzip":    write("plain.json.gz", []byte("{}")),
		"not JSON":    write("garbage.json.gz", gz(t, []byte("nope"))),
		"no version":  write("empty.json.gz", gz(t, []byte(`{"ResourceTypes":{"A":{}}}`))),
		"no types":    write("notypes.json.gz", gz(t, []byte(`{"ResourceSpecificationVersion":"1"}`))),
		"bad trailer": write("trunc.json.gz", gz(t, []byte(`{"ResourceSpecificationVersion":"1"}`))[:12]),
	} {
		if _, err := load(path); err == nil {
			t.Errorf("%s: load succeeded", name)
		}
	}
}

// TestRenderRefusesAnUnknownKind pins that a kind the emulator has no constant for fails the
// generation rather than emitting source that does not compile.
func TestRenderRefusesAnUnknownKind(t *testing.T) {
	_, err := render(snapshot{Version: "1", ResourceTypes: map[string]resourceType{
		"AWS::A::B": {Properties: map[string]property{"P": {Kind: "Quaternion"}}},
	}})
	if err == nil || !strings.Contains(err.Error(), "Quaternion") {
		t.Fatalf("render error = %v", err)
	}
	_, err = render(snapshot{Version: "1", ResourceTypes: map[string]resourceType{
		"AWS::A::B": {Attributes: map[string]string{"A": "Quaternion"}},
	}})
	if err == nil {
		t.Fatal("an unknown attribute kind rendered")
	}
}

// TestVendoredSnapshotIsCurrent is the drift check the CI job runs, as a test: the committed
// generated file is what the committed snapshot renders to.
func TestVendoredSnapshotIsCurrent(t *testing.T) {
	root := filepath.Join("..", "..")
	snap, err := load(filepath.Join(root, "emulator", "cfnschema", snapshotName))
	if err != nil {
		t.Fatal(err)
	}
	want, err := render(snap)
	if err != nil {
		t.Fatal(err)
	}
	got, err := os.ReadFile(filepath.Join(root, "emulator", "cfn_schema_gen.go"))
	if err != nil {
		t.Fatal(err)
	}
	if !bytes.Equal(got, want) {
		t.Fatal("emulator/cfn_schema_gen.go is out of date; run `make cfn-schema`")
	}
}

// TestRun walks the command's paths against a temporary snapshot: fetch, write, the up-to-date
// no-op, a passing and a failing check, and the failures it reports.
func TestRun(t *testing.T) {
	srv := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, _ *http.Request) {
		_, _ = w.Write([]byte(rawFixture))
	}))
	defer srv.Close()
	dir := t.TempDir()
	out := filepath.Join(dir, "gen.go")
	var stdout, stderr bytes.Buffer
	runWith := func(args ...string) int {
		stdout.Reset()
		stderr.Reset()
		return run(append([]string{"-data", dir, "-out", out}, args...), &stdout, &stderr)
	}

	if code := runWith("-check"); code != 1 {
		t.Fatalf("check without a snapshot = %d", code)
	}
	if code := runWith("-fetch", "-url", srv.URL); code != 0 {
		t.Fatalf("fetch = %d: %s", code, stderr.String())
	}
	if code := runWith("-check"); code != 1 || !strings.Contains(stderr.String(), "out of date") {
		t.Fatalf("check before generating = %d: %s", code, stderr.String())
	}
	if code := runWith(); code != 0 || !strings.Contains(stdout.String(), "updated") {
		t.Fatalf("generate = %d: %s%s", code, stdout.String(), stderr.String())
	}
	if code := runWith(); code != 0 || !strings.Contains(stdout.String(), "already up to date") {
		t.Fatalf("regenerate = %d: %s", code, stdout.String())
	}
	if code := runWith("-check"); code != 0 {
		t.Fatalf("check after generating = %d: %s", code, stderr.String())
	}
	if code := runWith("-fetch", "-url", srv.URL+"/missing\x7f"); code != 1 {
		t.Fatalf("a bad URL = %d", code)
	}
	if code := run([]string{"-nope"}, &stdout, &stderr); code != 2 {
		t.Fatalf("an unknown flag = %d", code)
	}
	if code := run([]string{"-data", dir, "-out", dir}, &stdout, &stderr); code != 1 {
		t.Fatalf("an unreadable output path = %d", code)
	}
}
